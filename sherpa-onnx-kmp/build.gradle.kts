    fun configurePortableBridgeInterop(
        targetName: String,
        nativeDirectory: String,
    ) {
        val target = when (targetName) {
            "iosArm64" -> iosArm64Target
            "iosSimulatorArm64" -> iosSimulatorArm64Target
            "macosArm64" -> macosArm64Target
            else -> error("Unsupported Apple target: $targetName")
        }
        val nativeLib = rootProject.layout.projectDirectory
            .dir("build/apple/$nativeDirectory/lib")
        target.compilations.getByName("main").cinterops.create("portableBridge") {
            defFile(project.file("src/nativeInterop/cinterop/portable-bridge.def"))
            includeDirs(rootProject.file("native/portable-bridge/include"))
        }
        target.binaries.all {
            linkerOpts(
                "-L${nativeLib.asFile.absolutePath}",
                "-lsherpa-onnx-kmp-apple",
                "-framework", "Foundation",
                "-framework", "CoreFoundation",
                "-framework", "Accelerate",
                "-framework", "CoreML",
                "-lc++",
            )
        }
    }

    configurePortableBridgeInterop("iosArm64", "ios-arm64")
    configurePortableBridgeInterop("iosSimulatorArm64", "ios-simulator-arm64")
    configurePortableBridgeInterop("macosArm64", "macos-arm64")

    fun KotlinNativeTarget.configureAppleFramework(konanTarget: String? = null) {
        binaries.framework {
            baseName = "SherpaOnnxKmp"
            binaryOption("bundleId", "com.k2fsa.sherpa.onnx.kmp")
            binaryOption("bundleShortVersionString", project.version.toString())
            binaryOption("bundleVersion", "1")
            if (konanTarget != null) {
                freeCompilerArgs += "-Xoverride-konan-properties=osVersionMin.$konanTarget=13.0"
            }
        }
    }
    iosArm64Target.configureAppleFramework()
    iosSimulatorArm64Target.configureAppleFramework()
    macosArm64Target.configureAppleFramework("macos_arm64")

